#!/usr/bin/env node
// ═══ SEC·D · SOC 2 EVIDENCE PACK ═════════════════════════════════════
// Emits a dated markdown pack an auditor can read: dependency inventory,
// table census, and the product-control checklist — each control checked
// by STATIC inspection of the shipped code, so the pack cannot claim a
// control that is not in the repo. Live-state evidence (chain intact,
// access review) comes from /api/security/* on a running instance; this
// script says so instead of pretending. The organizational checklist is
// printed as open work — the gap list is a generated artifact, not a
// promise.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const rd = (p) => readFileSync(join(root, p), "utf8");

const pkg = JSON.parse(rd("backend/package.json"));
const deps = Object.entries(pkg.dependencies || {}).sort(([a], [b]) => a.localeCompare(b));
const schema = rd("supabase/schema.sql");
const tables = (schema.match(/create table if not exists/gi) || []).length;

const CONTROLS = [
  ["CC6.1", "RBAC with per-module read/write", "backend/src/auth.js", /hasPerm/],
  ["CC6.1", "Department row-visibility enforced once in the CRUD rail", "backend/src/crud.js", /departmentId === scope/],
  ["CC6.1", "OIDC SSO; SAML refused at the schema level", "supabase/schema.sql", /kind[^\n]*'OIDC'/],
  ["CC6.1", "Login rate limiting", "backend/src/auth.js", /Too many login attempts/],
  ["CC6.1", "Forced password rotation on admin reset", "backend/src/auth.js", /mustChangePassword/],
  ["CC6.6", "Security headers + CORS lockdown", "backend/src/security.js", /X-Content-Type-Options/],
  ["CC6.7", "Secrets encrypted at rest with rotation", "backend/src/crypto.js", /rotate|encrypt/i],
  ["CC7.2", "Tamper-evident audit hash chain (seq, prevHash, rowHash)", "backend/src/audit.js", /verifyAuditChain/],
  ["CC7.2", "audit_log append-only trigger (UPDATE/DELETE raise)", "supabase/schema.sql", /trg_audit_immutable/],
  ["CC7.3", "Fault log records shape and hash, never payload contents", "backend/src/observability.js", /hash|shape/i],
  ["C1.2", "Data-subject erasure (anonymize) with legal-retention registry", "backend/src/erasure.js", /retain_legal|anonym/i],
  ["C1.2", "Data-subject export", "backend/src/erasure.js", /export/i],
  ["A1.2", "Instance export/restore with declared RESTORE_ORDER", "backend/src/routes/export.js", /RESTORE_ORDER/],
  ["CC4.1", "Access review generated live (dormant at 90d)", "backend/src/routes/security.js", /access-review/],
  ["A1.3", "Recovery drill: install→backup→wipe→restore→chain verified, one command", "backend/scripts/continuity-drill.mjs", /RECOVER Pulse/],
  ["CC1.4", "Continuity runbook, completeness CI-gated against scripts and docs", "backend/scripts/continuity-check.js", /CONTINUITY.md/],
];

const rows = CONTROLS.map(([cc, name, file, re]) => {
  let ok = false;
  try { ok = re.test(rd(file)); } catch { ok = false; }
  return { cc, name, file, ok };
});
const failed = rows.filter((r) => !r.ok);

const ORG = [
  "Security policy set, reviewed annually",
  "Risk assessment",
  "Vendor management + DPAs (Supabase, Vercel, Anthropic)",
  "Incident response runbook with a TESTED restore",
  "A NAMED second human holding credentials to every system in CONTINUITY.md\u2019s access register, who has run `npm run continuity:drill` on their own machine — the bus factor is one until this appointment is made; the runbook and drill are mitigations, not a substitute (TOP OPEN RISK, removed by an appointment, not a commit)",
  "Background checks & security awareness training",
  "On-call answerable by more than one person",
  "Engage auditor: Type I first, Type II after a 3–6 month evidence window",
];

const today = new Date().toISOString().slice(0, 10);
const md = `# SOC 2 Evidence Pack — Pulse (${today})

Generated by \`npm run soc2:evidence\`. Product controls below are verified by **static inspection of this repository at generation time** — a control absent from the code fails here. Live-state evidence (audit-chain verification, the current access review) is served by \`/api/security/audit-verify\` and \`/api/security/access-review\` on a running instance and is deliberately not asserted from a laptop.

## Software inventory
Production dependencies (${deps.length}):
${deps.map(([n, v]) => `- ${n} ${v}`).join("\n")}

Database: ${tables} tables (census enforced in CI by \`npm run docs:check\`).

## Product controls (static-verified)
| TSC | Control | Evidence | Status |
|---|---|---|---|
${rows.map((r) => `| ${r.cc} | ${r.name} | \`${r.file}\` | ${r.ok ? "✓ present" : "✗ NOT FOUND"} |`).join("\n")}

${failed.length ? `**${failed.length} control(s) not found — the pack refuses to bless them.**` : "All listed product controls verified present."}

## Organizational track (open — people and policies, not code)
${ORG.map((o) => `- [ ] ${o}`).join("\n")}
`;

const out = join(root, `SOC2-EVIDENCE-${today}.md`);
writeFileSync(out, md);
console.log(md);
console.log(`\n→ written to ${out}`);
if (failed.length) process.exit(1);
