// ═══ W4·H · THE TABLE CENSUS ══════════════════════════════════════════
// Documentation that cannot rot. Reads supabase/schema.sql, groups every
// table by territory, and writes the census block into ARCHITECTURE.md
// between its markers. `--check` fails (exit 1) when the written census
// disagrees with the schema — which is how a migration that forgets its
// documentation becomes a failing build rather than a stale paragraph.
import { readFileSync, writeFileSync } from "node:fs";
