export function tablesInSchema(sql) {
  return [...sql.matchAll(/create table if not exists\s+(\w+)\s*\(/gi)].map((m) => m[1]);
}

export function buildCensus(tables) {
  const owned = new Map();
  for (const [territory, , list] of TERRITORIES) for (const t of list) owned.set(t, territory);
  const groups = new Map(TERRITORIES.map(([t, purpose]) => [t, { purpose, tables: [] }]));
  const unclassified = [];
  for (const t of tables.slice().sort()) {
    const territory = owned.get(t);
    if (!territory) { unclassified.push(t); continue; }
    groups.get(territory).tables.push(t);
  }
  const lines = [`**${tables.length} tables** across ${TERRITORIES.length} territories. Generated by \`npm run docs:census\` — do not edit by hand.`, ""];
  lines.push("| Territory | Tables | Purpose |", "|---|---|---|");
  for (const [name, { purpose, tables: ts }] of groups) {
    if (!ts.length) continue;
    lines.push(`| **${name}** (${ts.length}) | ${ts.map((t) => `\`${t}\``).join(" · ")} | ${purpose} |`);
  }
  if (unclassified.length) {
    lines.push("", `> ⚠️ **UNCLASSIFIED (${unclassified.length}):** ${unclassified.map((t) => `\`${t}\``).join(", ")} — add each to TERRITORIES in \`backend/scripts/census.js\`.`);
  }
  return { body: lines.join("\n"), unclassified, count: tables.length };
}

function main() {
  const check = process.argv.includes("--check");
  const tables = tablesInSchema(readFileSync(SCHEMA, "utf8"));
  const { body, unclassified, count } = buildCensus(tables);
  const doc = readFileSync(DOC, "utf8");
  const i = doc.indexOf(START), j = doc.indexOf(END);
  if (i === -1 || j === -1) { console.error(`✗ ARCHITECTURE.md is missing ${START} / ${END} markers`); process.exit(1); }
  const current = doc.slice(i + START.length, j).trim();
  if (check) {
    const problems = [];
    if (unclassified.length) problems.push(`${unclassified.length} unclassified table(s): ${unclassified.join(", ")}`);
    if (current !== body.trim()) problems.push("census block is stale — run `npm run docs:census`");
    if (problems.length) { console.error("✗ census check failed:\n  - " + problems.join("\n  - ")); process.exit(1); }
    console.log(`✓ census current — ${count} tables, all classified`);
    return;
  }
  writeFileSync(DOC, doc.slice(0, i + START.length) + "\n" + body + "\n" + doc.slice(j));
  console.log(`✓ census written — ${count} tables${unclassified.length ? `, ${unclassified.length} UNCLASSIFIED` : ""}`);
}

if (process.argv[1] && process.argv[1].endsWith("census.js")) main();
